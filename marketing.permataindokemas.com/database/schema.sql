-- =============================================================================
-- PIK MARKETING CONTROL — Database schema
-- PT Permata Indo Kemas
--
-- Target  : MySQL 5.7+ / MySQL 8.x / MariaDB 10.3+
-- Charset : utf8mb4 (utf8mb4_unicode_ci)
--
-- Aman dijalankan berulang: semua tabel memakai CREATE TABLE IF NOT EXISTS
-- (tidak ada DROP TABLE). Untuk mengosongkan database gunakan
-- `php database/import_workbook.php --fresh ...` (lihat README).
--
-- Konvensi:
--   id          : surrogate key INT (dipakai untuk relasi/foreign key)
--   code        : ID bisnis yang stabil (mis. CUS-894EA1DA5F) — sama dengan ID
--                 di PIK_Master_Database_AppSheet.xlsx untuk data hasil migrasi
--   source_file / source_sheet / legacy_row : jejak asal data spreadsheet
--   legacy_*    : nilai asli spreadsheet (disimpan untuk audit, tidak dipakai
--                 sebagai sumber perhitungan)
-- =============================================================================

SET NAMES utf8mb4;

-- -----------------------------------------------------------------------------
-- USERS & SECURITY
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id                    INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code                  VARCHAR(20)  NOT NULL,
  name                  VARCHAR(120) NOT NULL,
  email                 VARCHAR(190) NOT NULL,
  password_hash         VARCHAR(255) NOT NULL,
  role                  ENUM('Admin','Marketing','Sales','Management','PPIC','Viewer') NOT NULL DEFAULT 'Viewer',
  is_active             TINYINT(1)   NOT NULL DEFAULT 1,
  must_change_password  TINYINT(1)   NOT NULL DEFAULT 0,
  last_login_at         DATETIME     NULL,
  password_changed_at   DATETIME     NULL,
  created_at            DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            DATETIME     NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_code (code),
  UNIQUE KEY uq_users_email (email),
  KEY idx_users_role (role, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_attempts (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  email         VARCHAR(190) NOT NULL,
  ip_address    VARCHAR(45)  NOT NULL,
  success       TINYINT(1)   NOT NULL DEFAULT 0,
  attempted_at  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_login_email (email, attempted_at),
  KEY idx_login_ip (ip_address, attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS settings (
  setting_key    VARCHAR(100) NOT NULL,
  setting_value  TEXT         NULL,
  updated_at     DATETIME     NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (setting_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

