-- -----------------------------------------------------------------------------
-- OPERATIONS: ORDER ENTRY FORM (purchase_orders + po_lines), DELIVERIES,
--             COMPLAINT & RETURN
-- Tabel purchase_orders menyimpan Order Entry Form (OEF). Data PO lama tetap
-- di tabel yang sama (order_number & ppic_status NULL).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_orders (
  id                    INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code                  VARCHAR(20)  NOT NULL,
  order_number          VARCHAR(30)  NULL COMMENT 'No. Order Entry Form (OEF-YYMM-NNNN)',
  po_number             VARCHAR(80)  NULL COMMENT 'No. PO dari customer',
  customer_id           INT UNSIGNED NULL COMMENT 'NULL hanya untuk data legacy yang customer-nya tidak ditemukan',
  sales_name            VARCHAR(120) NULL,
  sales_user_id         INT UNSIGNED NULL,
  po_date               DATE         NULL COMMENT 'Tanggal order',
  payment_term          VARCHAR(60)  NULL,
  product_spec          TEXT         NULL,
  is_subcont            TINYINT(1)   NOT NULL DEFAULT 0,
  supplier              VARCHAR(190) NULL,
  requested_date        DATE         NULL COMMENT 'Permintaan selesai / kirim',
  ship_to               VARCHAR(255) NULL COMMENT 'Tujuan kirim',
  status                ENUM('Open','On Process','Partial','Closed','Cancelled') NOT NULL DEFAULT 'Open',
  ppic_status           ENUM('Pending','Approved','Rejected') NULL COMMENT 'NULL = data lama (tanpa konfirmasi PPIC)',
  ppic_note             TEXT         NULL,
  ppic_by               INT UNSIGNED NULL,
  ppic_at               DATETIME     NULL,
  schedule_delivery_id  INT UNSIGNED NULL COMMENT 'Jadwal delivery otomatis dari OEF (FK ditambahkan oleh migrator)',
  legacy_status         VARCHAR(40)  NULL,
  remark         TEXT         NULL,
  source_file    VARCHAR(255) NULL,
  source_sheet   VARCHAR(100) NULL,
  legacy_row     INT          NULL,
  created_by     INT UNSIGNED NULL,
  updated_by     INT UNSIGNED NULL,
  created_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME     NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_po_code (code),
  KEY idx_po_number (po_number),
  KEY idx_po_customer (customer_id, po_date),
  KEY idx_po_status (status),
  KEY idx_po_date (po_date),
  UNIQUE KEY uq_po_order_number (order_number),
  KEY idx_po_ppic (ppic_status),
  CONSTRAINT fk_po_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
  CONSTRAINT fk_po_sales    FOREIGN KEY (sales_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_po_ppic_by  FOREIGN KEY (ppic_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_po_created  FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_po_updated  FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

