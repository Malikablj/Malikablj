def customer_decision(reject_to, alternatives=None, approve_to=None):
    return [
        {
            "key": "approved",
            "label": "Approved",
            "tone": "positive",
            "target": {"kind": "process", "key": approve_to} if approve_to else {"kind": "next"},
            "approval_status": "approved",
        },
        {
            "key": "not_approved",
            "label": "Not Approved",
            "tone": "negative",
            "target": {"kind": "process", "key": reject_to, "alternatives": alternatives or []},
            "approval_status": "rejected",
            "requires_comment": True,
        },
    ]


