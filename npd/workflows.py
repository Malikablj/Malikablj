def define(**kw) -> dict:
    """Membuat definisi proses dengan nilai default."""
    base = {
        "short_name": kw["name"],
        "description": "",
        "kind": "task",
        "actor_roles": [kw["pic_role"]],
        "upload_roles": kw.get("actor_roles", [kw["pic_role"]]),
        "is_mandatory": True,
        "loop_only": False,
        "requires_document": False,
        "required_doc_types": [],
        "suggested_doc_types": kw.get("required_doc_types", []),
        "requires_approval": False,
        "approval_type": None,
        "approver_type": None,
        "outcomes": [],
        "next_key": None,
        "waiting_type": "internal",
        "waiting_label": None,
        "default_next_action": f"Selesaikan {kw['name']}",
        "duration_days": 3,
        "branch_group": None,
        "branch": None,
        "folder": "Lainnya",
        "record_type": "general",
        "fields": [],
        "calendar_category": None,
        "custom": False,
    }
    base.update(kw)
    return base


def field(key, label, type="text", required=False, **kw) -> dict:
    """Satu isian form. type: text | textarea | number | date | select | multiselect | user | doc_revision."""
    return {"key": key, "label": label, "type": type, "required": required, **kw}


