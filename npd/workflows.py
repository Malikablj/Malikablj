"""Template workflow default (PRD §4 Subcont dan §5 New Mold).

Setiap proses adalah dictionary. Kunci penting:
- key / name / short_name    : identitas proses
- kind                        : "task" (dikerjakan lalu selesai), "decision" (punya pilihan hasil),
                                "finish" (penutupan project)
- pic_role / actor_roles      : role PIC default & role yang boleh mengerjakan
- requires_document / required_doc_types : dokumen wajib sebelum proses bisa diselesaikan
- outcomes                    : pilihan hasil untuk proses decision, beserta tujuan workflow:
      target = {"kind": "next"}                   -> lanjut ke proses berikutnya
      target = {"kind": "process", "key": "..."}  -> lompat ke proses tertentu
                 (jika proses tujuan ada di belakang = revision loop)
      target = {"kind": "repeat"}                 -> ulangi proses ini (status Problem)
      target = {"kind": "cancel"}                 -> project dibatalkan
- fields                      : isian form proses (lihat templates/projects/process_complete.html)

Admin dapat mengubah template lewat menu Pengaturan -> Workflow. Project yang sudah
berjalan tetap memakai salinan (snapshot) template versi saat project dibuat.
"""
